/**
 * Source mapping: turn "this literal, on this line of this file" into an exact,
 * verifiable span, and find that span again later without asking anyone.
 *
 * A mapping is {file, start, end, text, before, after}: the byte-exact literal
 * plus enough surrounding text to tell it from every other copy of the same
 * number. Before every write the span is re-checked against the file on disk;
 * if the file moved under us the anchors relocate it, and if they cannot do so
 * unambiguously the mapping is reported stale instead of guessed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { parseLiteral, TweakError } from './literal.mjs';

const MAX_FILE = 2 * 1024 * 1024;
const ANCHOR = 48;
const LINE_CAP = 120;
const MAX_ANCHOR = 192;
const DENY_DIRS = new Set(['node_modules', '.git', 'dist', 'build', 'out', '.next', '.nuxt', '.svelte-kit', '.turbo', '.cache', 'coverage', 'vendor', 'target', '__pycache__', '.venv', 'venv', 'bower_components', '.lets']);
const DENY_FILES = /^(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|npm-shrinkwrap\.json|composer\.lock|Cargo\.lock|poetry\.lock|\.env(\..*)?)$/i;
const ALLOW_EXT = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.mts', '.cts', '.json', '.css', '.scss', '.sass', '.less', '.html', '.htm', '.vue', '.svelte', '.astro', '.yaml', '.yml', '.toml', '.ini', '.cfg', '.py', '.rb', '.go', '.rs', '.java', '.kt', '.cs', '.lua', '.gd', '.php', '.swift', '.c', '.cpp', '.h', '.hpp']);
const GENERATED = /@generated|DO NOT EDIT|Code generated|auto-generated by|autogenerated/i;

/** Resolve `rel` inside `root`, refusing escapes, symlink escapes, vendored and generated files. Returns the real path. */
export function safePath(root, rel) {
  if (typeof rel !== 'string' || !rel || rel.includes('\0')) throw new TweakError('path', 'a file path is required');
  if (path.isAbsolute(rel) || /^[A-Za-z]:/.test(rel)) throw new TweakError('path', `"${rel}" must be relative to the project`);
  const parts = rel.split(/[\\/]+/);
  if (parts.includes('..')) throw new TweakError('path', `"${rel}" leaves the project`);
  for (const p of parts.slice(0, -1)) if (DENY_DIRS.has(p)) throw new TweakError('path', `"${rel}" is inside ${p}/, which Let's Tweak never edits`);
  const base = parts.at(-1);
  if (DENY_FILES.test(base) || /\.min\.(js|css)$|\.map$/i.test(base)) throw new TweakError('path', `"${rel}" is a lock, minified or secret file`);
  if (!ALLOW_EXT.has(path.extname(base).toLowerCase())) throw new TweakError('path', `"${rel}" is not a source file type Let's Tweak edits`);
  const realRoot = fs.realpathSync(root);
  let real;
  try { real = fs.realpathSync(path.resolve(realRoot, rel)); } catch { throw new TweakError('path', `"${rel}" does not exist`); }
  const within = path.relative(realRoot, real);
  if (within.startsWith('..') || path.isAbsolute(within)) throw new TweakError('path', `"${rel}" resolves outside the project`);
  if (within.split(path.sep).some((p) => DENY_DIRS.has(p))) throw new TweakError('path', `"${rel}" resolves into a vendored or build folder`);
  return real;
}

export function readSource(abs) {
  const st = fs.statSync(abs);
  if (!st.isFile()) throw new TweakError('path', 'not a regular file');
  if (st.size > MAX_FILE) throw new TweakError('path', 'file is larger than 2 MB');
  const content = fs.readFileSync(abs, 'utf8');
  if (GENERATED.test(content.slice(0, 1024))) throw new TweakError('path', 'file is marked as generated; edit its source instead');
  return content;
}

const isWord = (c) => c !== undefined && /[A-Za-z0-9_$.#]/.test(c);

/**
 * Resolve a discovery hint {file, line, literal, col?, nth?} to an anchored mapping.
 * The hint is where Claude saw the value; this makes it exact, or says why it cannot.
 */
export function resolveHint(content, hint) {
  const { literal } = hint;
  if (typeof literal !== 'string' || !literal) throw new TweakError('hint', 'literal is required');
  const parsed = parseLiteral(literal);
  if (!parsed) throw new TweakError('hint', `"${literal}" is not a literal Let's Tweak can edit (numbers, true/false, quoted text, #hex colors)`);
  const lines = content.split('\n');
  const line = Number(hint.line);
  if (!Number.isInteger(line) || line < 1 || line > lines.length) throw new TweakError('hint', `line ${hint.line} is outside the file (${lines.length} lines)`);
  const offsets = [];
  let acc = 0;
  for (const l of lines) { offsets.push(acc); acc += l.length + 1; }

  const found = (ln) => {
    const out = [];
    const text = lines[ln - 1];
    for (let i = text.indexOf(literal); i >= 0; i = text.indexOf(literal, i + 1)) {
      const startsOk = !isWord(text[i - 1]) || /^["'`]/.test(literal);
      const endsOk = !isWord(text[i + literal.length]) || /["'`]$/.test(literal);
      if (startsOk && endsOk) out.push({ ln, col: i + 1, start: offsets[ln - 1] + i });
    }
    return out;
  };

  let cands = found(line);
  let correctedLine = null;
  if (!cands.length) {
    // Claude may be a line or two off; accept a move only when it is unambiguous
    const near = [];
    for (let d = 1; d <= 2; d++) for (const ln of [line - d, line + d]) if (ln >= 1 && ln <= lines.length) near.push(...found(ln));
    if (near.length === 1) { cands = near; correctedLine = near[0].ln; }
    else if (near.length > 1) throw new TweakError('ambiguous', `"${literal}" is not on line ${line}, and appears several times just around it (lines ${[...new Set(near.map((n) => n.ln))].join(', ')}); give the exact line`);
    else throw new TweakError('hint', `"${literal}" was not found on line ${line} of ${hint.file}`);
  }
  if (cands.length > 1) {
    const pick = hint.col ? cands.find((c) => c.col === Number(hint.col)) : hint.nth ? cands[Number(hint.nth) - 1] : null;
    if (!pick) throw new TweakError('ambiguous', `"${literal}" appears ${cands.length} times on line ${cands[0].ln} (columns ${cands.map((c) => c.col).join(', ')}); give col or nth`);
    cands = [pick];
  }
  const start = cands[0].start;
  const end = start + literal.length;
  rejectUnarySign(content, start, parsed);
  return { ...anchorsAt(content, start, end), line: cands[0].ln, correctedLine };
}

/** `x = -5` with literal "5": changing it to 10 would flip the sign. Make the hint carry the minus. */
function rejectUnarySign(content, start, parsed) {
  if (parsed.kind !== 'number') return;
  let i = start - 1;
  if (content[i] !== '-' && content[i] !== '+') return;
  const op = content[i];
  i--;
  while (i >= 0 && (content[i] === ' ' || content[i] === '\t')) i--;
  const prev = content[i];
  const binary = prev !== undefined && /[\w)\]]/.test(prev);
  if (!binary) throw new TweakError('hint', `the literal is preceded by a unary "${op}"; include it in the literal (e.g. "${op}${content.slice(start, start + 4)}…") so the sign is not lost`);
}

/** Anchors long enough that before+text+after occurs exactly once in `content` (or the longest allowed). */
export function anchorsAt(content, start, end) {
  const text = content.slice(start, end);
  for (let n = ANCHOR; ; n = Math.min(n * 2, MAX_ANCHOR)) {
    const before = content.slice(Math.max(0, start - n), start);
    const after = content.slice(end, end + n);
    const unique = countOf(content, before + text + after, 2) === 1;
    if (unique || n >= MAX_ANCHOR) return { start, end, text, before, after, unique, ...lineContext(content, start, end) };
  }
}

/** The rest of the literal's own line: a second, shorter anchor that survives edits to the lines around it. */
function lineContext(content, start, end) {
  const nl = content.lastIndexOf('\n', start - 1);
  const nr = content.indexOf('\n', end);
  return {
    lineBefore: content.slice(Math.max(nl + 1, start - LINE_CAP), start),
    lineAfter: content.slice(end, nr < 0 ? Math.min(content.length, end + LINE_CAP) : Math.min(nr, end + LINE_CAP)),
  };
}

function countOf(hay, needle, cap) {
  let c = 0;
  for (let i = hay.indexOf(needle); i >= 0 && c < cap; i = hay.indexOf(needle, i + 1)) c++;
  return c;
}

/**
 * Where is the mapping now?
 *   ok       exactly where it was
 *   moved    the file changed around it; the anchors found it again, uniquely
 *   changed  the anchors are intact but the literal itself was edited outside (same kind of literal)
 *   lost     neither the literal nor its surroundings can be found
 *   ambiguous  the same surroundings appear more than once
 */
export function locate(content, m, kind) {
  if (content.slice(m.start, m.end) === m.text && content.slice(Math.max(0, m.start - m.before.length), m.start) === m.before && content.slice(m.end, m.end + m.after.length) === m.after) {
    return { status: 'ok', start: m.start, end: m.end, text: m.text };
  }
  const whole = m.before + m.text + m.after;
  const hits = [];
  for (let i = content.indexOf(whole); i >= 0 && hits.length < 2; i = content.indexOf(whole, i + 1)) hits.push(i);
  if (hits.length === 1) {
    const start = hits[0] + m.before.length;
    return { status: 'moved', start, end: start + m.text.length, text: m.text };
  }
  if (hits.length > 1) return { status: 'ambiguous' };
  // the literal may have been edited by hand: look for the anchors with a different literal of the same kind between them
  const cands = [];
  for (let i = content.indexOf(m.before); i >= 0 && cands.length < 3; i = content.indexOf(m.before, i + 1)) {
    const from = i + m.before.length;
    const q = m.after ? content.indexOf(m.after, from) : -1;
    if (q < 0 || q - from > 64) continue;
    const text = content.slice(from, q);
    const p = parseLiteral(text);
    if (p && p.kind === kind) cands.push({ start: from, end: q, text });
  }
  if (cands.length === 1) return { status: 'changed', ...cands[0] };
  if (cands.length > 1) return { status: 'ambiguous' };
  // the neighbouring lines were edited (so the long anchors no longer match): fall back to the literal's own line,
  // accepted only when that line context occurs exactly once and is distinctive enough to mean something
  const line = byLine(content, m, kind);
  return line || { status: 'lost' };
}

function byLine(content, m, kind) {
  const { lineBefore: b, lineAfter: a } = m;
  if (typeof b !== 'string' || typeof a !== 'string' || b.replace(/\s/g, '').length < 4) return null;
  const hits = [];
  for (let i = content.indexOf(b); i >= 0 && hits.length < 2; i = content.indexOf(b, i + 1)) {
    const from = i + b.length;
    const nl = content.indexOf('\n', from);
    const lineEnd = nl < 0 ? content.length : nl;
    const q = a ? content.indexOf(a, from) : lineEnd;
    if (q < 0 || q > lineEnd || q - from > 64) continue;
    const text = content.slice(from, q);
    const p = parseLiteral(text);
    if (p && p.kind === kind) hits.push({ start: from, end: q, text });
  }
  if (hits.length !== 1) return hits.length > 1 ? { status: 'ambiguous' } : null;
  return { status: hits[0].text === m.text ? 'moved' : 'changed', ...hits[0] };
}

export function splice(content, start, end, text) {
  return content.slice(0, start) + text + content.slice(end);
}
